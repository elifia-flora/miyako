/** 是不是繁体中文（台湾 / 香港） */
export function isHant(locale) {
  return locale === 'zh-TW' || locale === 'zh-HK';
}

/** 逐字换繁体；表里没有的字原样保留 */
export function toHant(text) {
  const s = String(text ?? '');
  let out = '';
  for (const ch of s) out += HANT_CHARS[ch] ?? ch;
  return out;
}
