export const DICT = { zh: ZH, 'zh-TW': ZH_TW, 'zh-HK': ZH_HK, en: EN, ja: JA };

/**
 * @param {unknown} v
 * @returns {v is string}
 */
export function isLocale(v) {
  return Object.prototype.hasOwnProperty.call(DICT, v);
}

/** 'zh-CN' / 'zh-Hans-CN' / 'EN-us' → 'zh' / 'en'；认不出的返回 null */
export function normalizeLocale(v) {
  // 先把 `zh_TW` 统一成 `zh-tw`：Windows 的系统语言偶尔带下划线
  const s = String(v ?? '').trim().toLowerCase().replace(/_/g, '-');
  if (!s) return null;
  /*
   * 繁体必须排在 `zh-` 之前判：否则 `zh-TW` 会被上面那条笼统的 `startsWith('zh-')`
   * 吃掉、落到简体上 —— 系统是繁体的人第一次打开就被判成简中。
   * 顺序：具体地区 → 语言+文字 → 笼统中文。
   */
  if (s === 'zh-tw' || s.startsWith('zh-tw-') || s === 'tw') return 'zh-TW';
  if (s === 'zh-hk' || s.startsWith('zh-hk-') || s.startsWith('zh-mo') || s === 'hk') return 'zh-HK';
  // `zh-Hant-HK` 这种「文字+地区」的写法：地区仍然优先
  if (s.startsWith('zh-hant-hk') || s.startsWith('zh-hant-mo')) return 'zh-HK';
  // 只说「繁体中文」没说地区（macOS 的「中文（繁體）」常见）：按台湾走
  if (s === 'zh-hant' || s.startsWith('zh-hant-')) return 'zh-TW';
  if (s === 'zh' || s.startsWith('zh-')) return 'zh';
  if (s === 'en' || s.startsWith('en-')) return 'en';
  if (s === 'ja' || s.startsWith('ja-')) return 'ja';
  // 旧版把日语也当「认不出」回落到中文；现在认了，`jp` 是常见的误写，一并收下
  if (s === 'jp' || s.startsWith('jp-')) return 'ja';
  return null;
}

/**
 * 首次启动按系统语言猜一个：只用「认得出来」的那些，
 * 认不出（法语、韩语…）就回落到中文 —— 这是这个库的主场语言。
 */
export function guessLocale(languages) {
  const list = Array.isArray(languages) ? languages : languages ? [languages] : [];
  for (const l of list) {
    const n = normalizeLocale(l);
    if (n) return n;
  }
  return DEFAULT_LOCALE;
}

/** 语言自己的 HTML lang 值，给 <html lang> 和字体回退用 */
export function htmlLang(locale) {
  return (LOCALES.find((l) => l.id === locale) ?? LOCALES[0]).htmlLang;
}

/**
 * 取文案。
 * @param {string} locale
 * @param {string} key
 * @param {Record<string, unknown>} [vars] 占位符值；带数字 `n` 时先试 .one/.other 变体
 */
export function t(locale, key, vars) {
  if (!key) return '';
  const table = DICT[isLocale(locale) ? locale : FALLBACK_LOCALE];
  const n = vars?.n;
  const form = typeof n === 'number' ? (n === 1 ? 'one' : 'other') : null;
  let s = form ? table[`${key}.${form}`] : undefined;
  if (s == null) s = table[key];
  // 英文缺键就回落到中文：宁可露出中文，也不要露出 key 或空白
  if (s == null) s = DICT[FALLBACK_LOCALE][key];
  if (s == null) return key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (whole, name) =>
    name in vars ? String(vars[name]) : whole
  );
}

/** 单复数写法：tn(locale, 'grid.cell', 3) → 「3 格」/「3 cells」 */
export function tn(locale, key, n) {
  return t(locale, key, { n });
}

/** 两个语言里键集不一致的部分，测试用（`.one/.other` 折回基键比较） */
export function keyDiff(a, b) {
  const base = (k) => k.replace(/\.(one|other)$/, '');
  const left = new Set(Object.keys(DICT[a] ?? {}).map(base));
  const right = new Set(Object.keys(DICT[b] ?? {}).map(base));
  return {
    missingInB: [...left].filter((k) => !right.has(k)).sort(),
    missingInA: [...right].filter((k) => !left.has(k)).sort(),
  };
}
