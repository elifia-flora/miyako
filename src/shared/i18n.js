/**
 * i18n.js — 界面文案的唯一来源
 *
 * 为什么自己写而不引 vue-i18n：
 *   这里需要的只有三件事 ——「按 key 取字符串」「{占位符}」「切语言后重渲染」。
 *   vue-i18n 会带进 40+ KB 与一套 SFC/插件装配，还得在主进程里另配一份实例；
 *   而我们的主进程也要发同一批文案（窗口标题、文件对话框、网易云提示），
 *   用一个纯 JS 模块反而两边都能直接 import，测试也能用 node --test 跑。
 *
 * 约定：
 *   - 键是**平铺的点分串**（`menu.file.register`），不开嵌套对象 —— 查找是 O(1)，
 *     漏键时报出来也是一行能 grep 到的字符串。
 *   - 英文词典里**不许出现汉字**（tests/i18n.test.mjs 会查），
 *     所以「漏翻的中文」不会静默混进英文界面。
 *   - 两个词典的键集必须一致，同样由测试保证。
 *   - 单复数：`{key}.one` / `{key}.other`。t() 收到数字 `n` 时先试变体，
 *     没有就退回基键（中文没有复数，只写基键即可）。
 *   - 词典分文件放：中文与英文在本文件里，**日语 `i18n.ja.js`**、
 *     **繁體台灣 `i18n.zh-TW.js`**、**繁體香港 `i18n.zh-HK.js`**（后者是生成物）。
 *     再加一门语言就照 `i18n.ja.js` 复制一份、在 `LOCALES` / `DICT` 里各加一行。
 */

